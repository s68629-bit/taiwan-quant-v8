def _clean(lst):
    seen, clean = set(), []
    for s in lst:
        s = s.strip()
        code = s.replace(".TW","")
        if s.endswith(".TW") and code.isdigit() and s not in seen:
            seen.add(s)
            clean.append(s)
    return clean

