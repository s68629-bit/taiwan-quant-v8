def _cache_fresh():
    if not os.path.exists(UNIVERSE_CACHE):
        return False
    return (time.time() - os.path.getmtime(UNIVERSE_CACHE)) / 86400 < UNIVERSE_CACHE_DAYS

def get_listed_stocks(force_refresh=False):
    """
    取得台灣上市股票代號列表
    優先：FinMind → 快取 → 備用清單
    """
    if not force_refresh and _cache_fresh():
        with open(UNIVERSE_CACHE, "r", encoding="utf-8") as f:
            data = json.load(f)
        stocks = data.get("stocks", [])
        logger.info("市場清單（快取）：%d 支", len(stocks))
        return stocks

    logger.info("從 FinMind 更新市場清單...")
    stocks = _fetch_from_finmind()

    if stocks and len(stocks) > 200:
        with open(UNIVERSE_CACHE, "w", encoding="utf-8") as f:
            json.dump({"stocks": stocks,
                       "updated": time.strftime("%Y-%m-%d"),
                       "source": "FinMind"}, f)
        logger.info("市場清單已更新：%d 支（FinMind）", len(stocks))
        return stocks

    # FinMind 失敗 → 使用擴充備用清單
    logger.warning("FinMind 取得失敗，使用備用清單（%d 支）", len(FALLBACK_STOCKS))
    return list(FALLBACK_STOCKS)

def _fetch_from_finmind():
    if not FINMIND_TOKEN:
        return []
    url     = "https://api.finmindtrade.com/api/v4/data"
    headers = {"Authorization": f"Bearer {FINMIND_TOKEN}"}
    params  = {"dataset": "TaiwanStockInfo"}
    try:
        r = requests.get(url, params=params, headers=headers, timeout=30)
        r.raise_for_status()
        d = r.json()
        if d.get("status") != 200 or not d.get("data"):
            return []
        df = pd.DataFrame(d["data"])
        if "market" in df.columns:
            df = df[df["market"] == "tse"]
        if "stock_id" not in df.columns:
            return []
        stocks = [s for s in df["stock_id"].astype(str)
                  if s.isdigit() and 3 <= len(s) <= 5 and not s.startswith("0")]
        return sorted(set(stocks))
    except Exception as e:
        logger.warning("FinMind 市場清單失敗：%s", e)
        return []

def get_stock_tw_format(stocks):
    return [s + ".TW" for s in stocks]

def get_universe_status():
    """供 Dashboard 顯示的市場清單狀態"""
    stocks = get_listed_stocks()
    source = "備用清單" if len(stocks) <= len(FALLBACK_STOCKS) + 10 else "FinMind"
    return {
        "count":  len(stocks),
        "source": source,
        "is_full": len(stocks) > 500,
    }

